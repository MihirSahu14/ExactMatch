"""Builds results.md from runs/. Never edit results.md by hand.

    python -m exactmatch.report

One row per (split, system, sample size): the latest run wins. ΔF1 is against s0 on the same split and size.
"""
import json
from datetime import datetime
from pathlib import Path

from exactmatch.evaluate import ROOT, RUNS

HEADER = ("| System | Queries (no match) | F1 | ΔF1 vs s0 | Precision | Recall | No-match acc | Recall@k "
          "| False / missed | Cost per 1k | p95 latency | Errors | Run |")


def _f(x, fmt=".3f"):
    return "–" if x is None else format(x, fmt)


def build(runs: Path = RUNS) -> str:
    latest = {}
    for p in sorted(runs.glob("*/metrics.json")):  # dir names start with a timestamp, so later runs overwrite
        cfg = json.loads((p.parent / "config.json").read_text())
        latest[(cfg["split"], cfg["limit"], cfg["system"])] = (p.parent.name, json.loads(p.read_text()))

    out = ["# Results", "", f"_Generated by `python -m exactmatch.report` at {datetime.now():%Y-%m-%d %H:%M}. "
           "Do not edit by hand._", ""]
    for split in ("test", "valid", "train"):
        groups = sorted({lim for s, lim, _ in latest if s == split}, key=lambda lim: lim or 10**9, reverse=True)
        for limit in groups:
            out += [f"## {split}" + (f" (random sample of {limit})" if limit else " (full)"), "", HEADER,
                    "|" + "---|" * (HEADER.count("|") - 1)]
            base = latest.get((split, limit, "s0"), (None, None))[1]
            for (s, lim, system), (run, m) in sorted(latest.items()):
                if (s, lim) != (split, limit):
                    continue
                delta = f"{m['f1'] - base['f1']:+.3f}" if base and system != "s0" else "–"
                out.append(
                    f"| `{system}` | {m['queries']} ({m['queries_no_match']}) | **{_f(m['f1'])}** | {delta} "
                    f"| {_f(m['precision'])} | {_f(m['recall'])} | {_f(m['no_match_acc'])} "
                    f"| {_f(m['recall_at_k'])} @{m['k']} | {m['false_matches']} / {m['missed_matches']} "
                    f"| ${_f(m['cost_per_1k_usd'])} | {_f(m['latency_p95_s'], '.2f')}s | {m['errors']} | `{run}` |")
            out.append("")
    out += ["Reproduce a row: `python -m exactmatch.evaluate --system <system> --split <split> [--limit N]`.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (ROOT / "results.md").write_text(build(), encoding="utf-8")
    print(f"wrote {ROOT / 'results.md'}")
