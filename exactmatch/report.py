"""Builds results.md and results/*.png charts from runs/. Never edit results.md by hand.

    python -m exactmatch.report

One row per (split, system, sample size): the latest run wins. ΔF1 is against s0 on the same split and size.
Charts use the "headline" group: the test group (else valid) with the most systems.
The iterations chart uses every valid run in time order, so each attempt shows up, not just the latest.
"""
import json
from datetime import datetime
from pathlib import Path

from exactmatch.evaluate import ROOT, RUNS

CHARTS = ROOT / "results"
HEADER = ("| System | Queries (no match) | F1 | ΔF1 vs s0 | Precision | Recall | No-match acc | Recall@k "
          "| False / missed | Cost per 1k | p95 latency | Errors | Run |")

# Validated categorical slots 1-3 (dataviz palette, all-pairs CVD-safe); aqua is <3:1, so every mark is labeled.
# Slot 4 (yellow) marks s4_groups: it uses the catalog's product groups, which define gold, so it never counts
# as "ours" in the headline (FINAL.md section 9).
FAMILIES = {"Our pipeline (open model)": "#2a78d6", "Big open model": "#eb6834", "Closed frontier (Claude)": "#1baf7a",
            "Uses catalog groups (separate)": "#eda100"}
INK, INK2, MUTED, GRID, AXIS, SURFACE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7", "#fcfcfb"


def family(system: str) -> str:
    return "Closed frontier (Claude)" if "claude" in system else "Big open model" if "big" in system \
        else "Uses catalog groups (separate)" if "groups" in system else "Our pipeline (open model)"


def _f(x, fmt=".3f"):
    return "–" if x is None else format(x, fmt)


def _load(runs: Path):
    """[(run_dir_name, config, metrics)] in time order (dir names start with a timestamp)."""
    out = []
    for p in sorted(runs.glob("*/metrics.json")):
        out.append((p.parent.name, json.loads((p.parent / "config.json").read_text()), json.loads(p.read_text())))
    return out


def _latest(all_runs):
    return {(c["split"], c["limit"], c["system"]): (name, m) for name, c, m in all_runs}


def headline_group(latest):
    groups = {}
    for split, limit, _ in latest:
        groups[(split, limit)] = groups.get((split, limit), 0) + 1
    if not groups:
        return None
    return max(groups, key=lambda g: (g[0] == "test", groups[g], g[1] or 10**9))


def build(runs: Path = RUNS, charts: list[str] = ()) -> str:
    all_runs = _load(runs)
    latest = _latest(all_runs)
    out = ["# Results", "", f"_Generated by `python -m exactmatch.report` at {datetime.now():%Y-%m-%d %H:%M}. "
           "Do not edit by hand._", ""]

    head = headline_group(latest)
    if head:
        rows = {sysname: m for (s, lim, sysname), (_, m) in latest.items() if (s, lim) == head}
        claude = rows.get("s0_claude")
        ours = {k: m for k, m in rows.items() if family(k) == "Our pipeline (open model)"}
        if claude and ours:
            best = max(ours, key=lambda k: ours[k]["f1"])
            b = ours[best]
            ratio = claude["cost_per_1k_usd"] / b["cost_per_1k_usd"] if b["cost_per_1k_usd"] else None
            out += [f"**Headline ({head[0]}, {rows[best]['queries']} queries):** best system of ours `{best}` "
                    f"reaches F1 {b['f1']:.3f} vs Claude Opus 5.5 at {claude['f1']:.3f} "
                    f"({b['f1'] / claude['f1']:.1%} of its F1)"
                    + (f" at {ratio:.0f}x lower cost per lookup." if ratio else "."), ""]
    if charts:
        out += ["## Charts", ""] + [f"![{c}](results/{c})" for c in charts] + [""]

    for split in ("test", "valid", "train"):
        groups = sorted({lim for s, lim, _ in latest if s == split}, key=lambda lim: lim or 10**9, reverse=True)
        for limit in groups:
            out += [f"## {split}" + (f" (random sample of {limit})" if limit else " (full)"), "", HEADER,
                    "|" + "---|" * (HEADER.count("|") - 1)]
            base = latest.get((split, limit, "s0"), (None, None))[1]
            for (s, lim, system), (run, m) in sorted(latest.items(), key=lambda kv: kv[0][2]):  # limit may be None
                if (s, lim) != (split, limit):
                    continue
                delta = f"{m['f1'] - base['f1']:+.3f}" if base and system != "s0" else "–"
                out.append(
                    f"| `{system}` | {m['queries']} ({m['queries_no_match']}) | **{_f(m['f1'])}** | {delta} "
                    f"| {_f(m['precision'])} | {_f(m['recall'])} | {_f(m['no_match_acc'])} "
                    f"| {_f(m['recall_at_k'])} @{m['k']} | {m['false_matches']} / {m['missed_matches']} "
                    f"| ${_f(m['cost_per_1k_usd'])} | {_f(m['latency_p95_s'], '.2f')}s | {m['errors']} | `{run}` |")
            out.append("")
    out += ["Reproduce a row: `python -m exactmatch.evaluate --system <system> --split <split> [--limit N]`.", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- charts

def _axes(plt, title, w=8, h=4.5):
    fig, ax = plt.subplots(figsize=(w, h), dpi=150, facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(AXIS)
    ax.tick_params(colors=MUTED, length=0, labelsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.set_title(title, loc="left", color=INK, fontsize=12, pad=14)
    return fig, ax


def _legend(ax, names):
    from matplotlib.patches import Patch
    ax.legend(handles=[Patch(color=FAMILIES[n], label=n) for n in FAMILIES if n in names], frameon=False,
              loc="upper left", bbox_to_anchor=(0, 1.02), ncol=3, fontsize=8, labelcolor=INK2)


def make_charts(runs: Path = RUNS, out_dir: Path = CHARTS) -> list[str]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams["font.family"] = ["Segoe UI", "DejaVu Sans", "sans-serif"]

    all_runs = _load(runs)
    latest = _latest(all_runs)
    head = headline_group(latest)
    if not head:
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = sorted((sysname, m) for (s, lim, sysname), (_, m) in latest.items() if (s, lim) == head)
    names = [s for s, _ in rows]
    colors = [FAMILIES[family(s)] for s in names]
    where = f"{head[0]}, {rows[0][1]['queries']} queries" + (" (fixed random sample)" if head[1] else "")
    made = []

    # 1. F1 per system: the ladder
    fig, ax = _axes(plt, f"Match F1 by system  ·  {where}")
    bars = ax.bar(names, [m["f1"] for _, m in rows], color=colors, width=0.55, edgecolor=SURFACE, linewidth=2)
    for b, (_, m) in zip(bars, rows):
        ax.text(b.get_x() + b.get_width() / 2, b.get_height() + 0.01, f"{m['f1']:.3f}", ha="center", va="bottom",
                color=INK, fontsize=9)
    ax.set_ylim(0, 1.08)
    ax.set_ylabel("F1 (match class)", color=INK2, fontsize=9)
    _legend(ax, {family(s) for s in names})
    fig.tight_layout()
    fig.savefig(out_dir / "f1_by_system.png", facecolor=SURFACE)
    made.append("f1_by_system.png")

    # 2-3. quality vs efficiency tradeoffs
    for key, label, fname in (("cost_per_1k_usd", "Cost per 1,000 lookups (USD, log scale)", "cost_vs_f1.png"),
                              ("latency_p95_s", "p95 latency per lookup (s, log scale)", "latency_vs_f1.png")):
        fig, ax = _axes(plt, f"F1 vs {'cost' if 'cost' in key else 'latency'}  ·  {where}")
        ax.grid(axis="x", color=GRID, linewidth=0.8)
        xs = [max(m[key], 1e-4) for _, m in rows]
        ax.scatter(xs, [m["f1"] for _, m in rows], s=90, c=colors, edgecolors=SURFACE, linewidths=2, zorder=3)
        for x, (s, m) in zip(xs, rows):
            ax.annotate(s, (x, m["f1"]), xytext=(8, 4), textcoords="offset points", color=INK, fontsize=9)
        ax.set_xscale("log")
        from matplotlib.ticker import FuncFormatter, LogLocator
        unit = (lambda v: f"${v:g}") if "cost" in key else (lambda v: f"{v:g}s")
        ax.xaxis.set_major_locator(LogLocator(subs=(1, 2, 5)))
        ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: unit(v)))
        ax.xaxis.set_minor_formatter(FuncFormatter(lambda v, _: ""))
        ax.set_xlim(min(xs) / 2, max(xs) * 2)
        ax.set_ylim(0, 1.08)
        ax.set_xlabel(label, color=INK2, fontsize=9)
        ax.set_ylabel("F1", color=INK2, fontsize=9)
        _legend(ax, {family(s) for s in names})
        fig.tight_layout()
        fig.savefig(out_dir / fname, facecolor=SURFACE)
        made.append(fname)

    # 4. where the errors are: precision / recall / no-match accuracy per system
    metrics = [("precision", "Precision"), ("recall", "Recall"), ("no_match_acc", "No-match accuracy")]
    shades = ["#2a78d6", "#eb6834", "#1baf7a"]
    fig, ax = _axes(plt, f"Precision, recall and no-match accuracy  ·  {where}", w=9)
    width = 0.8 / len(metrics)
    for j, ((key, label), color) in enumerate(zip(metrics, shades)):
        xs = [i + (j - 1) * width for i in range(len(rows))]
        vals = [m[key] or 0 for _, m in rows]
        ax.bar(xs, vals, width=width, color=color, label=label, edgecolor=SURFACE, linewidth=2)
        for x, v in zip(xs, vals):
            ax.text(x, v + 0.01, f"{v:.2f}", ha="center", va="bottom", color=INK2, fontsize=7)
    ax.set_xticks(range(len(rows)), names)
    ax.set_ylim(0, 1.12)
    ax.legend(frameon=False, loc="upper left", bbox_to_anchor=(0, 1.02), ncol=3, fontsize=8, labelcolor=INK2)
    fig.tight_layout()
    fig.savefig(out_dir / "quality_breakdown.png", facecolor=SURFACE)
    made.append("quality_breakdown.png")

    # 5. iterations: every valid run in time order
    valid = [(name, c, m) for name, c, m in all_runs if c["split"] == "valid"]
    if valid:
        fig, ax = _axes(plt, "Iterations  ·  F1 on valid, every run in order (tuning happens here, never on test)",
                        w=max(8, 0.9 * len(valid) + 3))
        ys = [m["f1"] for _, _, m in valid]
        ax.plot(range(len(valid)), ys, color=FAMILIES["Our pipeline (open model)"], linewidth=2, zorder=2)
        ax.scatter(range(len(valid)), ys, s=70, c=[FAMILIES[family(c["system"])] for _, c, _ in valid],
                   edgecolors=SURFACE, linewidths=2, zorder=3)
        best = max(range(len(ys)), key=ys.__getitem__)
        for i, y in enumerate(ys):
            if i in (0, best, len(ys) - 1):  # selective labels: first, best, latest
                ax.annotate(f"{y:.3f}", (i, y), xytext=(0, 8), textcoords="offset points", ha="center",
                            color=INK, fontsize=9)
        ax.set_xticks(range(len(valid)), [f"{c['system']}\n{n[9:11]}:{n[11:13]}" for n, c, _ in valid], fontsize=8)
        ax.set_ylim(0, 1.08)
        ax.set_ylabel("F1 (valid)", color=INK2, fontsize=9)
        fig.tight_layout()
        fig.savefig(out_dir / "iterations.png", facecolor=SURFACE)
        made.append("iterations.png")
    plt.close("all")
    return made


def write():
    charts = make_charts()
    (ROOT / "results.md").write_text(build(charts=charts), encoding="utf-8")
    print(f"wrote {ROOT / 'results.md'} and {len(charts)} charts in {CHARTS}")


if __name__ == "__main__":
    write()
